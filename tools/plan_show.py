"""Plan and verify a collision-free drone light show, then write the show file.

  python tools/plan_show.py --drones 800 --sequence grid:8,sphere:10,heart:10,star:10,ring:8 -o show.json
  python tools/plan_show.py --drones 800 --spacing 2 --min-sep 1.5 ...   (RTK show drones)

Every drone flies straight lines on one shared time profile, targets assigned optimally (CAPT), and the
whole show is sampled at 10 Hz. Exit code 1 (no file written) when any pair comes closer than --min-sep,
or the show leaves the ceiling / radius. Needs numpy + scipy.
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from dronebridge import show as showlib  # noqa: E402

COLORS = {"grid": "#00ff78", "sphere": "#3cc8ff", "heart": "#ff1e50", "star": "#ffd700", "ring": "#e60000"}


def parse_sequence(text):
    seq = []
    for item in text.split(","):
        name, _, hold = item.partition(":")
        name = name.strip()
        if name not in showlib.SHAPES:
            raise SystemExit(f"bilinmeyen şekil '{name}' (seçenekler: {', '.join(showlib.SHAPES)})")
        seq.append((name, float(hold or 8), COLORS.get(name, "#ffffff")))
    return seq


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--drones", type=int, default=800)
    ap.add_argument("--sequence", default="grid:8,sphere:10,heart:10,star:10,ring:8", help="shape:hold_s,...")
    ap.add_argument("--spacing", type=float, default=3.0, help="m between neighbours in every formation")
    ap.add_argument("--min-sep", type=float, default=2.0, help="m: closer than this anywhere in the show = fail")
    ap.add_argument("--show-alt", type=float, default=30.0, help="m: lowest drone of each formation")
    ap.add_argument("--launch-alt", type=float, default=10.0)
    ap.add_argument("--speed", type=float, default=5.0, help="m/s horizontal limit")
    ap.add_argument("--ceiling", type=float, default=120.0)
    ap.add_argument("--radius", type=float, default=300.0)
    ap.add_argument("--center", help="lat,lon[,amsl] of the show center (stored in the file)")
    ap.add_argument("-o", "--out", type=Path, default=Path("show.json"))
    ap.add_argument("--luau", type=Path, help="also write a Roblox ModuleScript (e.g. src/server/ShowData.luau)")
    args = ap.parse_args(argv)
    sys.stdout.reconfigure(encoding="utf-8")

    lim = showlib.Limits(v_h=args.speed, ceiling=args.ceiling, radius=args.radius)
    show = showlib.plan(args.drones, parse_sequence(args.sequence), spacing=args.spacing,
                        launch_alt=args.launch_alt, show_alt=args.show_alt, lim=lim)
    print(f"Şov: {show.n} drone, {len(show.keyframes)} anahtar kare, {show.duration / 60:.1f} dk, "
          f"formasyon aralığı {args.spacing:.1f} m, en az ayrım şartı {args.min_sep:.1f} m")
    for kf in show.keyframes:
        p = kf.positions
        size = p.max(axis=0) - p.min(axis=0)
        print(f"  {kf.t_arrive:6.1f} s  {kf.name:7s} {size[0]:5.0f}×{size[1]:4.0f}×{size[2]:4.0f} m  "
              f"üst {p[:, 2].max():5.1f} m  komşu {showlib.min_spacing(p):4.2f} m")
    rep = showlib.verify(show, args.min_sep, lim)
    print(f"Doğrulama (10 Hz): en yakın iki drone {rep.min_separation:.2f} m (t={rep.min_separation_t:.1f} s), "
          f"tavan {rep.max_alt:.0f} m, yarıçap {rep.max_radius:.0f} m")
    for p in rep.problems:
        print(f"  ✗ {p}")
    for t, a, b, d in rep.violations[:10]:
        print(f"    t={t:6.1f} s  drone {a + 1} ↔ {b + 1}: {d:.2f} m")
    if not rep.ok:
        print("Dosya yazılmadı.")
        return 1
    center = tuple(float(v) for v in args.center.split(",")) if args.center else None
    text = json.dumps(showlib.to_json(show, center), separators=(",", ":"))
    args.out.write_text(text, encoding="utf-8")
    print(f"  ✓ Çarpışma yok. {args.out} ({args.out.stat().st_size / 1024:.0f} KB)")
    if args.luau:
        args.luau.write_text("-- Generated by tools/plan_show.py — do not edit. Played by ShowPlayer.luau.\n"
                             f"return [==[{text}]==]\n", encoding="utf-8")
        print(f"  Roblox modülü: {args.luau}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
